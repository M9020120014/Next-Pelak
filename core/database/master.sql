-- ============================================================================
-- Master Database Setup Script
-- ============================================================================
-- این فایل تمام جداول و توابع را به ترتیب ایجاد می‌کند
-- 
-- نحوه اجرا:
--   psql -U htni_admin -d your_database -f master.sql
-- 
-- یا در psql:
--   \i master.sql
-- 
-- ترتیب اجرا مهم است:
--   1. ابتدا schemas (00)
--   2. سپس sequences (01) - باید قبل از جداول باشد
--   3. سپس جداول به ترتیب وابستگی (02-06)
--   4. سپس توابع (functions)
-- ============================================================================

\echo '============================================================================'
\echo 'شروع ایجاد ساختار دیتابیس...'
\echo '============================================================================'

-- ============================================================================
-- Schema Files (جداول)
-- ============================================================================

\echo ''
\echo '--- ایجاد Schemas (pelak + htni) ---'
\i schema/00_create_schema.sql

\echo ''
\echo '--- ایجاد Sequences ---'
\i schema/01_sequences.sql

\echo ''
\echo '--- ایجاد جداول پایه (selectortype, selector) ---'
\i schema/02_base_tables.sql

\echo ''
\echo '--- ایجاد جداول احراز هویت (users, refresh_tokens) ---'
\i schema/03_auth_tables.sql

\echo ''
\echo '--- ایجاد جداول محتوا (page) ---'
\i schema/04_content_tables.sql

\echo ''
\echo '--- ایجاد جداول نظرات (comments, comment_likes) ---'
\i schema/05_comments_tables.sql

\echo ''
\echo '--- ایجاد جداول پروژه (htni.selectortype, htni.selector, user_additional_info) ---'
\i schema/06_project_tables.sql

-- ============================================================================
-- Functions Files (توابع)
-- ============================================================================

\echo ''
\echo '--- ایجاد توابع احراز هویت ---'
\i functions/01_auth_functions.sql

\echo ''
\echo '--- ایجاد توابع محتوا ---'
\i functions/02_content_functions.sql

\echo ''
\echo '--- ایجاد توابع نظرات ---'
\i functions/03_comments_functions.sql

\echo ''
\echo '--- ایجاد توابع اطلاعات تکمیلی کاربر ---'
\i functions/04_user_functions.sql

-- ============================================================================
-- پایان
-- ============================================================================

\echo ''
\echo '============================================================================'
\echo 'ایجاد ساختار دیتابیس با موفقیت انجام شد!'
\echo '============================================================================'

